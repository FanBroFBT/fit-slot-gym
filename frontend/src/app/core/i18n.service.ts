@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly lang = signal<LangCode>((localStorage.getItem(LANG_KEY) as LangCode) || 'en');

  setLang(code: LangCode) {
    this.lang.set(code);
    localStorage.setItem(LANG_KEY, code);
  }

  t(key: string): string {
    return TRANSLATIONS[this.lang()]?.[key] ?? key;
  }

  tSpec(specialty: string): string {
    if (!specialty) return '';
    const key = `SPEC_${specialty.toUpperCase()}`;
    return TRANSLATIONS[this.lang()]?.[key] ?? specialty;
  }
}